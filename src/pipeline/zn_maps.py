"""Builds AutoDock4Zn affinity maps for a receptor, at request time.

Why this exists at all: Vina's default scoring function has no metal term, so it
cannot reproduce how a sulfonamide binds the carbonic anhydrase zinc. Re-docking
the crystal acetazolamide into 3HS4 with plain Vina scoring lands 5.5 A from the
crystal pose; with AutoDock4Zn it lands 1.6 A. The zinc chemistry lives in a
tetrahedral pseudo-atom (TZ) placed next to the zinc plus a set of zinc-specific
pair potentials, and both only reach the docking through precomputed grid maps.

Maps can only be generated by AutoGrid, which is not pip-installable, so the
previous version of this project built them offline for eight hand-picked
structures and committed 50 MB of gzipped maps. That is what limited the app to
those eight. Here a 117 KB AutoGrid 4.2.9 binary is vendored (GPL-2.0, see
src/bin/linux-x86_64/COPYING.autogrid) and the maps for whatever structure was
typed are built on demand in about ten seconds, then cached.

Reference: Santos-Martins, Forli, Ramos & Olson, J. Chem. Inf. Model. 2014, 54,
2371-2379.
"""
import os
import platform
import shutil
import subprocess
import sys
import tempfile
import threading
import time
from functools import lru_cache

from src.logger import logging
from src.pipeline.rcsb import StructureError

AD4ZN_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ad4zn")
BIN_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "bin")

CACHE_ROOT = os.path.join(tempfile.gettempdir(), "ca_maps")
SPACING = 0.375
AUTOGRID_TIMEOUT = 180

# The constants zinc_pseudo.py uses when run as a script: the Zn to TZ distance,
# the carboxylate averaging parameter from the paper's supporting information,
# and the cutoff within which a receptor atom counts as zinc-coordinated.
TZ_DISTANCE = 2.0
CARBOXYLATE_WEIGHT = 0.5
ZINC_SHELL_CUTOFF = 2.5

# Every type src/pipeline/ligand_prep.py can emit. All of them are built up
# front so the cached maps serve any later ligand without a rebuild.
LIGAND_TYPES = ["A", "C", "N", "NA", "OA", "S", "SA", "HD", "F", "Cl", "Br", "I", "P"]

# AutoDock4Zn pair potentials, from the AutoDock-Vina zinc docking tutorial.
ZN_PAIR_POTENTIALS = """\
nbp_r_eps 0.25 23.2135 12 6 NA TZ
nbp_r_eps 2.1   3.8453 12 6 OA Zn
nbp_r_eps 2.25  7.5914 12 6 SA Zn
nbp_r_eps 1.0   0.0    12 6 HD Zn
nbp_r_eps 2.0   0.0060 12 6 NA Zn
nbp_r_eps 2.0   0.2966 12  6  N Zn
"""

# A full map set is ~60 MB on disk. The serverless /tmp is 512 MB and shared with
# everything else, so only a few structures are kept and the oldest goes first.
MAX_CACHED_TARGETS = 4

_lock = threading.Lock()


VENDORED_DIR = os.path.join(BIN_DIR, "linux-x86_64")
# Where the binary is copied if it cannot be executed where it is shipped.
RUNTIME_BIN_DIR = os.path.join(tempfile.gettempdir(), "ca_bin")


def _executable_copy(source_dir, name):
    """Copies the binary and its libraries somewhere they can be executed.

    A deployment bundle is not guaranteed to be mounted with execute permission,
    and nothing in the code can tell in advance. Copying into the temp directory,
    which is writable and executable on every runtime this deploys to, turns a
    hard failure into a one-off cost of a few megabytes.
    """
    os.makedirs(RUNTIME_BIN_DIR, exist_ok=True)
    for entry in os.listdir(source_dir):
        if not (entry == name or ".so" in entry):
            continue
        destination = os.path.join(RUNTIME_BIN_DIR, entry)
        if not os.path.exists(destination):
            shutil.copy2(os.path.join(source_dir, entry), destination)
        os.chmod(destination, 0o755)
    return os.path.join(RUNTIME_BIN_DIR, name)


@lru_cache(maxsize=1)
def autogrid_binary():
    """The vendored AutoGrid for this platform, or None if there is not one.

    Only linux-x86_64 is shipped, which is what the serverless runtime is. Local
    development on another platform falls back to an `autogrid4` on PATH.
    """
    if platform.system() == "Linux" and platform.machine() in ("x86_64", "AMD64"):
        candidate = os.path.join(VENDORED_DIR, "autogrid4")
        if os.path.exists(candidate):
            if not os.access(candidate, os.X_OK):
                try:
                    os.chmod(candidate, 0o755)
                except OSError:
                    pass
            if os.access(candidate, os.X_OK):
                return candidate
            logging.warning("the vendored AutoGrid is not executable in place; "
                            "copying it to the temp directory")
            try:
                return _executable_copy(VENDORED_DIR, "autogrid4")
            except OSError as e:
                logging.error(f"could not stage AutoGrid for execution: {e}")
    return shutil.which("autogrid4")


def _library_path():
    """The directory holding libstdc++, libgomp and libgcc_s for AutoGrid."""
    staged = os.path.join(RUNTIME_BIN_DIR, "libstdc++.so.6")
    return RUNTIME_BIN_DIR if os.path.exists(staged) else VENDORED_DIR


def _run_autogrid(binary, workdir, prefix):
    """Runs AutoGrid with the vendored GCC runtime libraries on the search path.

    The binary needs libstdc++, libgomp and libgcc_s. Those are shipped next to
    it rather than assumed, because what a serverless base image happens to
    carry is not something to bet a feature on.
    """
    environment = dict(os.environ)
    library_dir = _library_path()
    if os.path.isdir(library_dir):
        existing = environment.get("LD_LIBRARY_PATH")
        environment["LD_LIBRARY_PATH"] = f"{library_dir}:{existing}" if existing else library_dir
    # AutoGrid parallelises over OpenMP threads; the function has one vCPU.
    environment.setdefault("OMP_NUM_THREADS", "1")

    try:
        completed = subprocess.run(
            [binary, "-p", f"{prefix}.gpf", "-l", f"{prefix}.glg"],
            cwd=workdir, capture_output=True, text=True, timeout=AUTOGRID_TIMEOUT,
            env=environment)
    except subprocess.TimeoutExpired:
        raise StructureError("Building the zinc force-field maps timed out.")
    if completed.returncode != 0:
        log = ""
        log_path = os.path.join(workdir, f"{prefix}.glg")
        if os.path.exists(log_path):
            with open(log_path) as f:
                log = f.read()[-2000:]
        logging.error(f"autogrid4 failed: {completed.stderr[-1000:]}\n{log}")
        raise StructureError("The zinc force-field maps could not be built for "
                             "this structure.")


def _grid_points(size):
    points = int(round(size / SPACING))
    return points + (points % 2)  # AutoGrid requires an even number of points


def _receptor_types(pdbqt_path):
    with open(pdbqt_path) as f:
        return sorted({l[77:79].strip() for l in f if l.startswith(("ATOM", "HETATM"))})


@lru_cache(maxsize=1)
def _zinc_pseudo_module():
    """Loads the vendored zinc_pseudo.py as a module.

    It is a script that calls main() at import and reads sys.argv, so it is
    loaded once with a harmless argv and its functions are used directly
    afterwards. Running it as `sys.executable zinc_pseudo.py` is what the
    obvious implementation does, and that fails in a serverless function, where
    sys.executable is not a Python the function can re-launch.
    """
    import importlib.util

    path = os.path.join(AD4ZN_DIR, "zinc_pseudo.py")
    spec = importlib.util.spec_from_file_location("ca_zinc_pseudo", path)
    module = importlib.util.module_from_spec(spec)
    saved_argv = sys.argv
    sys.argv = ["zinc_pseudo.py", "-h"]   # prints usage, then exits
    try:
        spec.loader.exec_module(module)
    except SystemExit:
        pass
    finally:
        sys.argv = saved_argv
    return module


def _add_zinc_pseudo_atoms(receptor_path, out_path):
    """Adds the tetrahedral TZ pseudo-atoms around each zinc.

    This is the reference implementation from AutoDock-Vina (Apache-2.0,
    vendored under ad4zn/), driven in-process.
    """
    zinc_pseudo = _zinc_pseudo_module()
    try:
        atoms, existing_tz, last_serial, non_atom_text = zinc_pseudo.load_pdbqt(receptor_path)
        pseudo_atoms = []
        for group in zinc_pseudo.bruteNearbyAtoms(atoms):
            shell = zinc_pseudo.znShell(group[0], ZINC_SHELL_CUTOFF, CARBOXYLATE_WEIGHT)
            shell.proc_rec(group[1:])
            pseudo = shell.tetrahedral_pseudo(TZ_DISTANCE)
            if pseudo is not None:
                pseudo_atoms.append(pseudo)
        for pseudo in pseudo_atoms:
            last_serial += 1
            pseudo.serial = last_serial
            atoms.append(pseudo)
        with open(out_path, "w") as f:
            for position, atom in enumerate(atoms):
                for line in non_atom_text.get(position, []):
                    f.write(line)
                f.write(atom.getline())
    except Exception as e:
        logging.error(f"zinc_pseudo failed on {os.path.basename(receptor_path)}: {e!r}")
        raise StructureError("The zinc pseudo-atom site could not be built.")

    if "TZ" not in _receptor_types(out_path):
        raise StructureError(
            "No tetrahedral zinc site was found in this structure. The zinc is "
            "present but not in the geometry AutoDock4Zn models.")
    return out_path


def _evict_old_targets(keep):
    """Keeps /tmp bounded: drops all but the most recently used map sets."""
    if not os.path.isdir(CACHE_ROOT):
        return
    entries = []
    for name in os.listdir(CACHE_ROOT):
        path = os.path.join(CACHE_ROOT, name)
        if os.path.isdir(path) and name != keep:
            entries.append((os.path.getmtime(path), path))
    entries.sort(reverse=True)
    for _, path in entries[MAX_CACHED_TARGETS - 1:]:
        shutil.rmtree(path, ignore_errors=True)
        logging.info(f"evicted cached maps at {path}")


def build(receptor, force=False):
    """Returns the map prefix Vina loads for this receptor, building it if needed.

    Serialised across threads: two concurrent requests for the same structure
    would otherwise run AutoGrid into the same directory.
    """
    binary = autogrid_binary()
    if binary is None:
        raise StructureError(
            "Docking is unavailable: no AutoGrid binary for this platform.")

    pdb_id = receptor.pdb_id
    prefix_name = f"{pdb_id}_tz"
    target_dir = os.path.join(CACHE_ROOT, pdb_id)
    prefix_path = os.path.join(target_dir, prefix_name)
    field = f"{prefix_path}.maps.fld"

    with _lock:
        expected = [f"{prefix_path}.{t}.map" for t in LIGAND_TYPES]
        expected += [field, f"{prefix_path}.e.map", f"{prefix_path}.d.map"]
        if not force and all(os.path.exists(p) and os.path.getsize(p) for p in expected):
            os.utime(target_dir, None)  # mark as recently used for eviction
            return prefix_path

        started = time.time()
        os.makedirs(CACHE_ROOT, exist_ok=True)
        _evict_old_targets(keep=pdb_id)
        workdir = tempfile.mkdtemp(prefix=f"{pdb_id}_grid_", dir=CACHE_ROOT)

        tz_receptor = _add_zinc_pseudo_atoms(
            receptor.path, os.path.join(workdir, f"{prefix_name}.pdbqt"))
        shutil.copy(os.path.join(AD4ZN_DIR, "AD4Zn.dat"), workdir)

        centre = " ".join(f"{c:.3f}" for c in receptor.box_centre)
        points = " ".join(str(_grid_points(s)) for s in receptor.box_size)
        maps = "".join(f"map {prefix_name}.{t}.map\n" for t in LIGAND_TYPES)
        gpf = (
            f"npts {points}\n"
            f"parameter_file AD4Zn.dat\n"
            f"gridfld {prefix_name}.maps.fld\n"
            f"spacing {SPACING}\n"
            f"receptor_types {' '.join(_receptor_types(tz_receptor))}\n"
            f"ligand_types {' '.join(LIGAND_TYPES)}\n"
            f"receptor {prefix_name}.pdbqt\n"
            f"gridcenter {centre}\n"
            f"smooth 0.5\n"
            f"{maps}"
            f"elecmap {prefix_name}.e.map\n"
            f"dsolvmap {prefix_name}.d.map\n"
            f"dielectric -0.1465\n"
            f"{ZN_PAIR_POTENTIALS}"
        )
        with open(os.path.join(workdir, f"{prefix_name}.gpf"), "w") as f:
            f.write(gpf)

        _run_autogrid(binary, workdir, prefix_name)

        # Publish atomically: a half-written map set must never look complete.
        shutil.rmtree(target_dir, ignore_errors=True)
        os.replace(workdir, target_dir)
        missing = [p for p in expected if not os.path.exists(p)]
        if missing:
            raise StructureError(
                f"AutoGrid did not produce {len(missing)} of the expected maps.")
        logging.info(f"{pdb_id}: built {len(LIGAND_TYPES) + 2} AD4Zn maps in "
                     f"{time.time() - started:.1f}s")
        return prefix_path
